let currentLang = 'ru';
try {
  const saved = localStorage.getItem('fantasy_lang');
  if (saved && dictionary[saved]) {
    currentLang = saved;
  }
} catch (e) {}

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (dictionary[lang]) {
    currentLang = lang;
    try {
      localStorage.setItem('fantasy_lang', lang);
    } catch (e) {}
  }
  return currentLang;
}

export function t(key, params = {}) {
  const dict = dictionary[currentLang] || dictionary.ru;
  let text = dict[key] || dictionary.ru[key] || key;
  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
  }
  return text;
}
